-- Apply once after backing up the database. Existing tables/data are unchanged.
-- Distinct expenditure declarations and incoming-return claims; not a payment system.
CREATE TABLE project_reconciliations (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 version BIGINT NOT NULL DEFAULT 0,
 project_id BIGINT NOT NULL,
 kind VARCHAR(20) NOT NULL,
 declaration_id BIGINT NULL,
 amount DECIMAL(15,2) NOT NULL,
 released_amount DECIMAL(15,2) NOT NULL,
 status VARCHAR(20) NOT NULL,
 submitted_by BIGINT NOT NULL,
 submitted_at DATETIME(6) NOT NULL,
 note VARCHAR(2000) NOT NULL,
 file_path VARCHAR(1000) NOT NULL,
 file_name VARCHAR(200) NOT NULL,
 file_type VARCHAR(100) NOT NULL,
 file_size BIGINT NOT NULL,
 return_destination VARCHAR(1500) NULL,
 transfer_reference VARCHAR(100) NULL,
 transferred_on DATE NULL,
 reviewed_by BIGINT NULL,
 reviewed_at DATETIME(6) NULL,
 review_note VARCHAR(2000) NULL,
 receipt_reference VARCHAR(100) NULL,
 receipt_key VARCHAR(100) NULL,
 UNIQUE KEY uq_reconciliation_receipt (receipt_key),
 KEY ix_reconciliation_project (project_id),
 CONSTRAINT fk_reconciliation_project FOREIGN KEY (project_id) REFERENCES projects(id),
 CONSTRAINT fk_reconciliation_declaration FOREIGN KEY (declaration_id) REFERENCES project_reconciliations(id),
 CONSTRAINT fk_reconciliation_provider FOREIGN KEY (submitted_by) REFERENCES users(id),
 CONSTRAINT fk_reconciliation_reviewer FOREIGN KEY (reviewed_by) REFERENCES users(id),
 CONSTRAINT ck_reconciliation_kind CHECK (kind IN ('DECLARATION','RETURN')),
 CONSTRAINT ck_reconciliation_status CHECK (status IN ('PENDING','APPROVED','REJECTED')),
 CONSTRAINT ck_reconciliation_amount CHECK (amount >= 0 AND released_amount >= amount AND (kind = 'DECLARATION' OR amount > 0))
);
